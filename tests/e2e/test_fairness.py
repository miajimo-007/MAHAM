"""Score fairness: To Do finish/cancel, quick wins (own only, locked after approval), shadow work (own, 3 days),
locked months read-only — in the app and in hand-edited files."""
import json
from harness import app_session, Check, run, SHOTS
async def add_to_file(s, who, recs):
    name = who + '.json'
    existing = await s.js(f"(async () => {{ try {{ const f = await (await Store.usersDir.getFileHandle('{name}')).getFile(); return JSON.parse(await f.text()).records; }} catch (e) {{ return []; }} }})()")
    ids = {r['id'] for r in recs}
    payload = json.dumps({'version': 1, 'kind': 'user', 'user': who, 'records': [r for r in existing if r['id'] not in ids] + recs})
    await s.js(f"(async () => {{ const fh = await Store.usersDir.getFileHandle('{name}', {{create: true}}); const w = await fh.createWritable(); await w.write({json.dumps(payload)}); await w.close(); }})()")
async def main():
    c = Check('score fairness')
    async with app_session() as s:
        pg = s.page; J = s.js
        toast = lambda: pg.inner_text('#toasts')
        d = lambda n: J(f"U.addDays(U.todayStr(), {n})")
        # ---------- To Do ----------
        await s.sign_in_as('apps-mgr')
        await J(f"Store.save({{c: 'todo', id: 'td-f', task: 'Update order set', analyst: 'yousef', assigned: '{await d(-5)}', duration: 2, status: 'In Progress'}})"); await J("Store.flush()")
        await s.sign_in_as('yousef')
        await J("UI.editRecord('todo', Store.get('td-f'))"); await pg.wait_for_selector('#recform'); await pg.wait_for_timeout(300)
        opts = await pg.eval_on_selector_all('#recform [name=status] option', 'os => os.map(o => o.value)')
        c('analyst cannot pick "Canceled"', 'Canceled' not in opts, opts)
        await J("UI.closeModal()")
        await J("Store.save(Object.assign({}, Store.get('td-f'), {status: 'Canceled'}))")
        c('cancel refused', await J("Store.get('td-f').status") == 'In Progress' and 'cancel' in (await toast()).lower())
        await J(f"Store.save(Object.assign({{}}, Store.get('td-f'), {{finish: '{await d(2)}'}}))")
        c('future finish refused', not await J("Store.get('td-f').finish"))
        await J(f"Store.save(Object.assign({{}}, Store.get('td-f'), {{finish: '{await d(-7)}'}}))")
        c('finish before it was given refused', not await J("Store.get('td-f').finish"))
        await J(f"Store.save(Object.assign({{}}, Store.get('td-f'), {{duration: 30}}))")
        c("analyst cannot change the manager's due date", await J("Store.get('td-f').duration") == 2)
        # backdated finish needs a reason (in the form)
        await J("UI.editRecord('todo', Store.get('td-f'))"); await pg.wait_for_selector('#recform'); await pg.wait_for_timeout(300)
        await pg.fill('#recform [name=finish]', await d(-4)); await pg.click('[data-save]'); await pg.wait_for_timeout(500)
        c('earlier finish date without a reason: form stays open with a message', await pg.locator('#recform').count() == 1 and 'Reason for an earlier finish date' in await toast())
        await pg.fill('#recform [name=finishNote]', 'Finished on Sunday, forgot to update'); await pg.click('[data-save]'); await pg.wait_for_selector('#recform', state='detached', timeout=8000)
        r = await J("Store.get('td-f')")
        c('…with a reason it saves (manager can see why)', r['finish'] == await d(-4) and r['status'] == 'Ready for review' and r['finishNote'].startswith('Finished'))
        # hand-edited file: cancels his late To Do
        await s.sign_in_as('apps-mgr'); await J(f"Store.save({{c: 'todo', id: 'td-h', task: 'Late task', analyst: 'yousef', assigned: '{await d(-9)}', duration: 1, status: 'In Progress'}})"); await J("Store.flush()")
        h = await J("Store.get('td-h')")
        await add_to_file(s, 'yousef', [dict(h, status='Canceled', duration=40, _ts=await J('Date.now()'), _by='yousef')])
        await J("Store.sync(true)")
        r = await J("Store.get('td-h')")
        c('hand-edited cancel + longer due date are undone', r['status'] == 'In Progress' and r['duration'] == 1, r)
        c('…and flagged in System Check', any('cancel' in x['why'] for x in await J("Store.rejected")))
        # ---------- Quick wins ----------
        await s.sign_in_as('yousef')
        await J(f"Store.save({{c: 'quickwin', id: 'qw-k', analyst: 'layla', date: U.todayStr(), subject: 'For Layla'}})")
        c("quick win for someone else refused", not await J("Store.get('qw-k')") and 'yourself' in await toast())
        await J(f"Store.save({{c: 'quickwin', id: 'qw-a', analyst: 'yousef', date: U.todayStr(), subject: 'Faster triage form', expected: '{await d(5)}', status: 'In-Progress'}})")
        await J("Store.save(Object.assign({}, Store.get('qw-a'), {approval: 'Accepted', qwId: 'QW-999'}))")
        c('analyst cannot approve his own quick win', not await J("Store.get('qw-a').approval"))
        await s.sign_in_as('apps-mgr'); await J("Store.save(Object.assign({}, Store.get('qw-a'), {approval: 'Accepted', qwId: 'QW-001'}))")
        await s.sign_in_as('yousef')
        await J(f"Store.save(Object.assign({{}}, Store.get('qw-a'), {{subject: 'Something bigger', expected: '{await d(-40)}'}}))")
        c('after approval: subject / dates locked', await J("Store.get('qw-a').subject") == 'Faster triage form' and 'locked' in await toast())
        await J("Store.save(Object.assign({}, Store.get('qw-a'), {status: 'Completed'}))")
        c('…status can still be updated', await J("Store.get('qw-a').status") == 'Completed')
        await J("UI.editRecord('quickwin', Store.get('qw-a'))"); await pg.wait_for_selector('#recform')
        c('the form shows the lock', 'details are locked' in await pg.inner_text('#modal')); await J("UI.closeModal()")
        # ---------- Shadow work ----------
        await J("Store.save({c: 'shadow', id: 'sw-k', analyst: 'layla', date: U.todayStr(), taskType: 'Support', subject: 'x', minutes: 600})")
        c('shadow work for someone else refused', not await J("Store.get('sw-k')"))
        await J(f"Store.save({{c: 'shadow', id: 'sw-f', analyst: 'yousef', date: '{await d(1)}', taskType: 'Support', subject: 'x', minutes: 60}})")
        c('future date refused', not await J("Store.get('sw-f')"))
        await J(f"Store.save({{c: 'shadow', id: 'sw-o', analyst: 'yousef', date: '{await d(-9)}', taskType: 'Support', subject: 'x', minutes: 60}})")
        c('9 days back refused (limit 7)', not await J("Store.get('sw-o')") and '7 days' in await toast())
        await J(f"Store.save({{c: 'shadow', id: 'sw-ok', analyst: 'yousef', date: '{await d(-5)}', taskType: 'Support', subject: 'Called ward', minutes: 45}})")
        c('5 days back is fine', bool(await J("Store.get('sw-ok')")))
        await s.sign_in_as('apps-mgr'); await J(f"Store.save({{c: 'shadow', id: 'sw-m', analyst: 'yousef', date: '{await d(-10)}', taskType: 'Support', subject: 'Added by manager', minutes: 30}})")
        c('the manager can add older entries for an analyst', bool(await J("Store.get('sw-m')")))
        # ---------- Locked month ----------
        lm = await J("(() => { const d = U.pd(U.todayStr()); d.setDate(1); d.setMonth(d.getMonth() - 1); return U.ds(d); })()")
        await J(f"Store.save({{c: 'todo', id: 'td-l', task: 'Last month task', analyst: 'yousef', assigned: '{lm}', duration: 3, status: 'In Progress'}})")
        await J(f"Store.save({{c: 'scoresnap', id: 'snap-x-yousef', analyst: 'yousef', year: {lm[:4]}, month: {int(lm[5:7])}, score: 90}})"); await J("Store.flush()")
        await s.sign_in_as('yousef')
        await J("Store.save(Object.assign({}, Store.get('td-l'), {comment: 'late note', finish: U.todayStr()}))")
        c('locked month: analyst change refused', not await J("Store.get('td-l').comment") and 'locked' in await toast())
        await J("UI.editRecord('todo', Store.get('td-l'))"); await pg.wait_for_selector('#recform')
        t = await pg.inner_text('#modal'); c('…the form says the month is locked and is read-only', 'is locked' in t and await pg.locator('#recform [data-save], [data-save]').count() == 0)
        await pg.screenshot(path=f'{SHOTS}/locked_month.png'); await J("UI.closeModal()")
        await add_to_file(s, 'yousef', [dict(await J("Store.get('td-l')"), comment='hand edit', _ts=await J('Date.now()'), _by='yousef')]); await J("Store.sync(true)")
        c('…a hand-edited change after the lock is ignored', not await J("Store.get('td-l').comment"))
        await s.sign_in_as('apps-mgr'); await J("Store.save(Object.assign({}, Store.get('td-l'), {comment: 'manager note'}))")
        c('the manager can still change a locked month', await J("Store.get('td-l').comment") == 'manager note')
        c.done(s)
run(main())
