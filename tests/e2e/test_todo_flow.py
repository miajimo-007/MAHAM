"""8 Nov: hand-on chains — "➜ Send on" makes a NEW To Do for the next person (filled-in form); the person before counts as
done once handed on; the next person can "↩ Send back" (the To Do before reopens until "✓ Fixed", then it is back with
them); workflows built by the super admin hand on by themselves (named person, or chosen by the one finishing), with
"a comment is needed", "send back to the work"; the trust check accepts a workflow's step To Do only when it matches;
every step is scored as a To Do of its own person."""
from harness import app_session, Check, run

async def main():
    c = Check('hand-on chains and workflows')
    async with app_session() as s:
        pg = s.page; J = s.js
        st = lambda i: J(f"(() => {{ const r = Store.get('{i}'); const d = Calc.todoDerive(r); return {{ status: d.status, finish: TodoFlow.view(r) ? TodoFlow.view(r).finish : r.finish, label: TodoFlow.label(r), phase: TodoFlow.phase(r) }}; }})()")
        nxt = lambda i: J(f"(TodoFlow.nextOf(Store.get('{i}')) || {{}})")
        act = lambda who, i, a, extra='{}': J(f"(() => {{ const was = App.me; App.me = '{who}'; try {{ TodoFlow.act(Store.get('{i}'), '{a}', {extra}); }} finally {{ App.me = was; }} }})()")
        # ---------- the super admin builds a workflow ----------
        await s.go('#/admin/work/todo', 500)
        await pg.fill('#tfwtypes', 'Order set change, Report request'); await pg.click('#tfwtsave'); await pg.wait_for_timeout(300)
        await pg.click('#tfwex'); await pg.wait_for_selector('#tfwf')
        await pg.check('#modal [data-tfwty="Order set change"]'); await pg.select_option('#modal [name=swho0]', 'm:layla')
        await pg.click('#modal [data-ok]'); await pg.wait_for_timeout(300)
        wf = await J("TodoFlow.defs()[0]")
        c('workflow saved (Validation → Testing)', wf and [x['name'] for x in wf['steps']] == ['Validation', 'Testing'] and wf['steps'][0]['who'] == 'm:layla' and wf['steps'][1]['who'] == 'pick' and wf['steps'][1]['needNote'] and wf['steps'][1]['backTo'] == '0', wf)
        # ---------- by hand: manager → Yousef → manager sends on → a new To Do for Layla ----------
        await J("""Store.saveMany([{ c: 'todo', id: 'tf-m', analyst: 'yousef', team: 'apps', task: 'Update the discharge template', assigned: U.addDays(U.todayStr(), -3), duration: 5, status: 'In Progress', givenBy: 'apps-mgr' }])""")
        await s.sign_in_as('yousef', 'analyst'); await J("todoDone('tf-m')"); await J("Store.flush()")
        await s.sign_in_as('apps-mgr', 'analyst'); await s.go('#/todo', 400)
        c('manager sees ➜ Send on next to Confirm', await pg.locator('[data-tf="send|tf-m"]').count() == 1 and await pg.locator('[data-tdok="tf-m"]').count() == 1)
        await pg.click('[data-tf="send|tf-m"]'); await pg.wait_for_selector('#recform [name=task]')
        c('Send on opens a new To Do form, filled in', 'Update the discharge template' in await pg.input_value('#recform [name=task]') and 'Handed on from' in await pg.inner_text('#recform'))
        c('no "Repeat" when handing on', await pg.locator('#recform [name=repeat]').count() == 0)
        await pg.fill('#recform [name=task]', 'Testing: test the discharge template on 3 wards'); await pg.select_option('#recform [name=analyst]', 'layla'); await pg.fill('#recform [name=duration]', '2')
        await pg.click('#modal [data-save]'); await pg.wait_for_timeout(400)
        t2 = await nxt('tf-m')
        c('a real To Do for Layla, linked to Yousef\'s', t2.get('analyst') == 'layla' and t2.get('prevStep') == 'tf-m' and t2.get('stepNo') == 1 and t2.get('stepName') == 'Testing' and t2.get('duration') == 2, t2)
        x = await st('tf-m'); c("Yousef's part counts as done once handed on", x['status'] == 'Resolved' and 'Handed on to Layla' in x['label'], x)
        c('nothing left for the manager to confirm on it', not await J("Store.canConfirmTodo(Store.get('tf-m'), 'apps-mgr')"))
        t2id = t2['id']; await J("Store.flush()")
        # Layla: it is her own To Do
        await s.sign_in_as('layla', 'analyst'); t = await s.go('#/home', 500)
        c("on Layla's My Day as her To Do", 'Testing: test the discharge template' in t)
        await s.go('#/todo', 400)
        c('her To Do List: ✓ Done and ↩ Send back', await pg.locator(f'[data-done="{t2id}"]').count() == 1 and await pg.locator(f'[data-tf="back|{t2id}"]').count() == 1)
        # wrong people cannot send back
        await act('sara', 'tf-m', 'back', f"{{ from: '{t2id}', note: 'x' }}"); await act('yousef', 'tf-m', 'back', f"{{ from: '{t2id}', note: 'x' }}")
        c('a send-back by anyone else is ignored', (await st('tf-m'))['status'] == 'Resolved')
        await pg.click(f'[data-tf="back|{t2id}"]'); await pg.wait_for_selector('#tfb'); await pg.fill('#tfb [name=note]', 'The allergy section is missing'); await pg.click('#modal [data-ok]'); await pg.wait_for_timeout(300)
        x = await st('tf-m'); c("send back: Yousef's To Do is open again", x['status'] == 'In Progress' and 'Sent back by Layla' in x['label'], x)
        c("Layla's waits for the fix", "Waiting for Yousef" in (await st(t2id))['label'])
        await J("Store.flush()")
        await s.sign_in_as('yousef', 'analyst'); t = await s.go('#/home', 500)
        c('Yousef sees it on My Day with the reason', 'The allergy section is missing' in t)
        await s.go('#/todo', 400); await pg.click('[data-tf="redo|tf-m"]'); await pg.wait_for_selector('#tfr'); await pg.click('#modal [data-ok]'); await pg.wait_for_timeout(300)
        x = await st('tf-m'); c('fixed: done again, finish = the fix', x['status'] == 'Resolved' and x['finish'] == await J("U.todayStr()"), x)
        c('back with Layla', 'Waiting' not in (await st(t2id))['label'])
        await J("Store.flush()")
        await s.sign_in_as('layla', 'analyst'); await J(f"todoDone('{t2id}')"); await J("Store.flush()")
        await s.sign_in_as('apps-mgr', 'analyst')
        c('last one goes to the manager to confirm', await J(f"Store.canConfirmTodo(Store.get('{t2id}'), 'apps-mgr')"))
        await J("UI.editRecord('todo', Store.get('tf-m'))"); await pg.wait_for_selector('#tflow')
        tl = await pg.inner_text('#tflow'); c('the form shows the chain', all(w in tl for w in ['Yousef', 'Layla', 'Testing', 'sent back', 'fixed']), tl[:300])
        await J("UI.closeModal()")
        # ---------- workflow: hands on by itself ----------
        await J("UI.editRecord('todo')"); await pg.wait_for_selector('#recform')
        await pg.fill('#recform [name=task]', 'Add new insulin order set'); await pg.select_option('#recform [name=analyst]', 'yousef'); await pg.select_option('#recform [name=ttype]', 'Order set change')
        c('the type picks the workflow', await pg.input_value('#recform [name=wf]') == wf['id'])
        await pg.click('#modal [data-save]'); await pg.wait_for_timeout(300)
        wid = await J("Store.all('todo', '*').find(t => t.task === 'Add new insulin order set').id"); await J("Store.flush()")
        await s.sign_in_as('yousef', 'analyst'); await J(f"todoDone('{wid}')"); await pg.wait_for_timeout(300)
        v1 = await nxt(wid)
        c('finishing hands on by itself: Validation To Do for Layla', v1.get('analyst') == 'layla' and v1.get('stepName') == 'Validation' and v1.get('id') == f'todo-step-{wid}-a' and v1.get('task', '').startswith('Validation: Add new insulin'), v1)
        c("Yousef's counts as done", (await st(wid))['status'] == 'Resolved')
        # a step To Do that does not match the workflow is ignored
        await J(f"Store.save(Object.assign(TodoFlow.stepCopy(Store.get('{wid}'), 'nora'), {{ id: 'todo-step-tf-m-a', prevStep: 'tf-m' }}))")
        await J("Store.flush()"); await J("Store.sync(true)"); await pg.wait_for_timeout(300)
        c("the workflow's step To Do passes the trust check", await J(f"!!Store.get('todo-step-{wid}-a')"))
        c('a made-up step To Do is ignored', await J("!Store.get('todo-step-tf-m-a')"))
        await J("Store.flush()")
        # Layla finishes Validation → the next step is "chosen": she picks Nora
        await s.sign_in_as('layla', 'analyst'); await J(f"todoDone('todo-step-{wid}-a')"); await pg.wait_for_selector('#tfk [name=to]', timeout=5000)
        await pg.select_option('#tfk [name=to]', 'nora'); await pg.click('#modal [data-ok]'); await pg.wait_for_timeout(300)
        v2 = await nxt(f'todo-step-{wid}-a')
        c('she chose Nora: a Testing To Do for Nora', v2.get('analyst') == 'nora' and v2.get('stepName') == 'Testing' and v2.get('stepNo') == 2, v2)
        await J("Store.flush()"); await J("Store.sync(true)"); await pg.wait_for_timeout(300)
        c('accepted by the trust check', await J(f"!!Store.get('{v2.get('id')}')"))
        await J("Store.flush()")
        # Nora: send back goes to the work (Yousef), not to Layla (workflow setting)
        await s.sign_in_as('nora', 'analyst')
        c('send back from Testing goes to the work', await J(f"TodoFlow.backTarget(Store.get('{v2.get('id')}')).id") == wid)
        await act('nora', wid, 'back', f"{{ from: '{v2.get('id')}', note: 'Dose rounding wrong' }}")
        c("Yousef's To Do reopens", (await st(wid))['status'] == 'In Progress' and (await st(f'todo-step-{wid}-a'))['status'] == 'Resolved')
        await J("Store.flush()"); await s.sign_in_as('yousef', 'analyst'); await act('yousef', wid, 'done'); await J("Store.flush()")
        await s.sign_in_as('nora', 'analyst')
        # a comment is needed to finish Testing
        await J(f"todoDone('{v2.get('id')}')"); await pg.wait_for_timeout(300)
        c('Testing needs a comment to finish', await J(f"!Store.get('{v2.get('id')}').finish") and await pg.locator('#recform').count() == 1)
        await J("UI.closeModal()")
        await J(f"(() => {{ const r = Object.assign({{}}, Store.get('{v2.get('id')}'), {{ comment: 'Tested on 5 patients', finish: U.todayStr() }}); Schemas.todo.beforeSave(r); Store.save(r); }})()"); await J("Store.flush()")
        await s.sign_in_as('apps-mgr', 'analyst')
        c('last step → manager confirms', await J(f"Store.canConfirmTodo(Store.get('{v2.get('id')}'), 'apps-mgr')"))
        # ---------- teams and scoring ----------
        await s.sign_in_as('lab-mgr', 'analyst')
        c("another team's manager has no Send on", await J(f"TodoFlow.buttons(Store.get('{v2.get('id')}'), {{ sendOn: true }})") == '' and not await J(f"Store.canConfirmTodo(Store.get('{v2.get('id')}'), 'lab-mgr')"))
        await s.sign_in_as('adam', 'admin')
        cnt = await J("(() => { const y = +U.todayStr().slice(0, 4), m = +U.todayStr().slice(5, 7); const P = Calc.perf(y); const n = id => (P.members[id] || {})[m] ? P.members[id][m].todo : 'not scored'; return { yousef: n('yousef'), layla: n('layla'), nora: n('nora') }; })()")
        c('every step is a To Do of its own person (Yousef 2, Layla 2, Nora 1)', cnt == {'yousef': 2, 'layla': 2, 'nora': 1}, cnt)
        c('no page errors', not s.errors, s.errors[:3])
        c.done(s)

run(main())
