"""Project workflows: admin builds one; moves, who may move, approval, conditions, stuck alert, history, stage removal."""
from harness import app_session, Check, run, SHOTS
async def main():
    c = Check('project workflows')
    async with app_session() as s:
        pg = s.page; J = s.js
        # --- admin builds the example workflow
        t = await s.go('#/admin/workflows', 500)
        c('Workflows tab', 'No workflows yet' in t)
        await pg.click('#wfex'); await pg.wait_for_timeout(400)
        c('editor with stages, grid and rules', await pg.locator('.wf-st tr[data-si]').count() == 7 and await pg.locator('.wf-grid [data-mv]').count() == 42 and await pg.locator('.wf-rules tr[data-mi]').count() > 5)
        await pg.screenshot(path=f'{SHOTS}/workflow_editor.png', full_page=True)
        # tick an extra move: Dev → Done, then untick it
        await pg.check('[data-mv="dev>done"]'); await pg.wait_for_timeout(200)
        c('ticking adds a rule row', 'Dev → Done' in (await pg.inner_text('.wf-rules')).replace('\n', ' ').replace('  ', ' ') or await pg.locator('.wf-rules tr[data-mi]').count() > 15)
        await pg.uncheck('[data-mv="dev>done"]'); await pg.wait_for_timeout(200)
        opts = await J("[...document.querySelectorAll('.wf-rules [data-ma] option')].slice(0, 6).map(o => o.textContent)")
        c('approval by titles only', opts == ['No approval', 'Project owner', 'Team leader', 'Team manager', 'Director', 'AED'], str(opts))
        c('no names in approval lists', await J("![...document.querySelectorAll('.wf-rules [data-ma] option')].some(o => o.value.startsWith('m:'))"))
        await pg.click('#wfsave'); await pg.wait_for_timeout(500)
        c('saved', await J("Flow.list().length") == 1 and await J("Flow.list()[0].name") == 'Enhancement (SRS)')
        wid = await J("Flow.list()[0].id")
        # --- a project on it (owner: Yousef, member Layla)
        await J(f"Store.save({{id:'pw1', c:'project', name:'Order sets SRS', team:'apps', manager:'yousef', members:['layla'], start:U.todayStr(), status:'Not Started', priority:'Normal', progress:0}})")
        await J(f"UI.editRecord('project', Store.get('pw1'))"); await pg.wait_for_selector('#recform')
        c('workflow field in the project form', await pg.locator('#recform [name=workflow]').count() == 1)
        await pg.select_option('#recform [name=workflow]', wid); await pg.click('[data-save]'); await pg.wait_for_timeout(500)
        c('starts in To Do', await J("Store.get('pw1').stage") == 'todo' and await J("Store.get('pw1').status") == 'Not Started')
        # --- member Layla cannot move To Do → In Analysis (owner/manager only)
        await s.sign_in_as('layla'); t = await s.go('#/project/pw1', 500)
        c('stage bar shown', 'Workflow · Enhancement (SRS)' in t)
        c('member has no move from To Do', await pg.locator('[data-flto]').count() == 0)
        # --- owner Yousef moves to In Analysis, then condition blocks Dev
        await s.sign_in_as('yousef'); await s.go('#/project/pw1', 500)
        c('owner sees allowed moves only', await pg.locator('[data-flto]').count() == 3)   # analysis, hold, rejected
        await pg.click('[data-flto="analysis"]'); await pg.wait_for_selector('#mvf'); await pg.click('.modal [data-ok]'); await pg.wait_for_timeout(400)
        c('moved to In Analysis', await J("Store.get('pw1').stage") == 'analysis' and await J("Store.get('pw1').status") == 'In Progress')
        await s.go('#/home', 200); await s.go('#/project/pw1', 400)
        await pg.click('[data-flto="dev"]'); await pg.wait_for_selector('#mvf')
        c('conditions listed', 'Write the description' in await pg.inner_text('.modal') and 'Set a target date' in await pg.inner_text('.modal'))
        c('move button disabled', await pg.is_disabled('.modal [data-ok]'))
        await J("UI.closeModal()")
        await J("Store.save(Object.assign({}, Store.get('pw1'), {description:'Review all order sets', due:U.addDays(U.todayStr(), 30)}))")
        await s.go('#/home', 200); await s.go('#/project/pw1', 400)
        await pg.click('[data-flto="dev"]'); await pg.wait_for_selector('#mvf'); await pg.click('.modal [data-ok]'); await pg.wait_for_timeout(400)
        c('moved to Dev', await J("Store.get('pw1').stage") == 'dev')
        # member moves Dev → UAT (allowed for members)
        await s.sign_in_as('layla'); await s.go('#/project/pw1', 400)
        await pg.click('[data-flto="uat"]'); await pg.wait_for_selector('#mvf'); await pg.click('.modal [data-ok]'); await pg.wait_for_timeout(400)
        c('member moved Dev → UAT', await J("Store.get('pw1').stage") == 'uat')
        # UAT → Dev needs a comment
        await s.go('#/home', 200); await s.go('#/project/pw1', 400)
        await pg.click('[data-flto="dev"]'); await pg.wait_for_selector('#mvf'); await pg.click('.modal [data-ok]'); await pg.wait_for_timeout(300)
        c('comment required', await J("Store.get('pw1').stage") == 'uat')
        await J("UI.closeModal()")
        # --- owner asks UAT → Done: needs the manager's approval
        await s.sign_in_as('yousef'); await s.go('#/project/pw1', 400)
        await pg.click('[data-flto="done"]'); await pg.wait_for_selector('#mvf')
        c('approval note shown', 'needs' in await pg.inner_text('.modal') and 'approval' in await pg.inner_text('.modal'))
        await pg.fill('.modal [name=note]', 'UAT signed off'); await pg.click('.modal [data-ok]'); await pg.wait_for_timeout(400)
        c('waits for approval, stage unchanged', await J("Store.get('pw1').stage") == 'uat' and await J("Store.get('pw1').pending.approver") == 'apps-mgr')
        await s.sign_in_as('apps-mgr'); t = await s.go('#/home', 500)
        c("manager's My work has the approval", 'Approve: Order sets SRS → Done' in t)
        await s.go('#/project/pw1', 400); await pg.click('[data-flno]'); await pg.wait_for_selector('#rjf'); await pg.fill('#rjf [name=why]', 'Attach the sign-off'); await pg.click('.modal [data-ok]'); await pg.wait_for_timeout(400)
        c('rejected → back with reason', not await J("Store.get('pw1').pending") and await J("Store.get('pw1').history.some(x => x.rejected && x.note === 'Attach the sign-off')"))
        await s.sign_in_as('yousef'); t = await s.go('#/project/pw1', 400)
        c('owner sees the rejection', 'rejected moving to Done' in t)
        await pg.click('[data-flto="done"]'); await pg.wait_for_selector('#mvf'); await pg.click('.modal [data-ok]'); await pg.wait_for_timeout(300)
        await s.sign_in_as('apps-mgr'); await s.go('#/project/pw1', 400); await pg.click('[data-flok]'); await pg.wait_for_timeout(400)
        p = await J("Store.get('pw1')")
        c('approved → Done', p['stage'] == 'done' and p['status'] == 'Done' and p['progress'] == 100 and p['history'][-1]['approvedBy'] == 'apps-mgr')
        await s.go('#/home', 200); t = await s.go('#/project/pw1', 400)
        await pg.click('.fl-hist summary'); await pg.wait_for_timeout(200)
        c('history and time in stage', 'approved by' in await pg.inner_text('.fl-hist') and 'UAT' in await pg.inner_text('.fl-hist'))
        await pg.screenshot(path=f'{SHOTS}/workflow_project.png', full_page=True)
        # --- stuck alert
        await s.sign_in_as('adam')
        await J(f"Store.save({{id:'pw2', c:'project', name:'Lab interface', team:'apps', manager:'yousef', workflow:'{wid}', stage:'uat', stageSince: Date.now() - 15*864e5, status:'In Progress', start:U.todayStr(), priority:'Normal', progress:0}})")
        await s.sign_in_as('yousef'); t = await s.go('#/home', 500)
        c('owner My work: stuck in UAT', 'Lab interface — 15 days in UAT' in t)
        t = await s.go('#/projects', 400); c('projects list flags it', 'UAT' in t and '15d' in t)
        # --- admin override and removing a stage in use
        await s.sign_in_as('adam'); await s.go('#/project/pw2', 400)
        await pg.select_option('#flany', 'hold'); await pg.wait_for_selector('#mvf'); await pg.click('.modal [data-ok]'); await pg.wait_for_timeout(400)
        c('admin can move anywhere (recorded)', await J("Store.get('pw2').stage") == 'hold' and await J("Store.get('pw2').history.slice(-1)[0].override") == True)
        await s.go('#/admin/workflows', 400); await pg.click(f'[data-wfedit="{wid}"]'); await pg.wait_for_timeout(300)
        idx = await J(f"Flow.get('{wid}').statuses.findIndex(s => s.id === 'hold')")
        await pg.click(f'[data-sdel="{idx}"]'); await pg.wait_for_selector('#mapf')
        await pg.select_option('#mapf [name=to]', 'dev'); await pg.click('.modal [data-ok]'); await pg.wait_for_timeout(300)
        await pg.click('#wfsave'); await pg.wait_for_timeout(500)
        c('stage removed, its project moved to Dev', await J(f"!Flow.get('{wid}').statuses.some(s => s.id === 'hold')") and await J("Store.get('pw2').stage") == 'dev')
        # --- not a super admin: cannot change workflows
        await s.sign_in_as('apps-mgr'); await J("Store.save(Object.assign({}, Store.get('settings-workflows'), {list: []}))"); await pg.wait_for_timeout(200)
        c('only the admin can change workflows', await J("Flow.list().length") == 1)
        c.done(s)
run(main())
