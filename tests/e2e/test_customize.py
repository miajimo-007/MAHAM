"""Admin → Customize: name everywhere, tagline, colour, menu, words, targets, weekend, sign-in message, report header,
start page, My Day tiles, restore default, export/import bundle."""
from harness import app_session, Check, run, SHOTS
async def main():
    c = Check('customize')
    async with app_session() as s:
        pg = s.page; J = s.js
        await s.sign_in_as('adam', 'admin'); t = await s.go('#/admin/custom', 600)
        c('Customize tab opens', 'Name, logo, tagline and colour' in t and 'Words used in the app' in t and 'Start page' in t)
        await pg.screenshot(path=f'{SHOTS}/customize.png', full_page=True)
        # name + tagline + colour
        await pg.fill('#cz-look [name=appName]', 'MAHAMMI'); await pg.fill('#cz-look [name=tagline]', 'Work that counts.')
        await pg.locator('.cz-sw:has(input[value=purple])').click()
        await pg.locator('[data-csave=look]').click(); await pg.wait_for_timeout(500)
        nav = await J("document.querySelector('nav').innerText")
        c('app name in the menu group and About item', 'MAHAMMI' in nav.upper() and 'About MAHAMMI' in nav, nav[-120:])
        c('browser tab uses the name', 'MAHAMMI' in await J("document.title"))
        c('purple accent applied', await J("getComputedStyle(document.documentElement).getPropertyValue('--accent').trim()") == '#6d3fd0')
        # menu: rename To Do List + icon + group, move Shadow Works to the top
        await s.go('#/admin/custom', 400)
        await pg.fill('.cz-item[data-k=todo] .cz-lb', 'My Tasks'); await pg.fill('.cz-item[data-k=todo] .cz-ic', '✅')
        await pg.fill('.cz-grp[data-g=Work] .cz-gname', 'Daily work')
        for _ in range(2): await pg.locator('.cz-item[data-k=shadow] [data-up]').click()
        await pg.locator('[data-csave=menu]').click(); await pg.wait_for_timeout(500)
        order = await J("[...document.querySelectorAll('nav a[data-nav]')].map(a => a.dataset.nav)")
        nav = await J("document.querySelector('nav').innerText")
        c('renamed page + icon + group name in the menu', 'My Tasks' in nav and '✅' in nav and 'DAILY WORK' in nav.upper())
        c('Shadow Works moved first in its group', order.index('shadow') < order.index('home'), order)
        t = await s.go('#/todo', 400); c('page title follows the new name', await J("document.querySelector('#ptitle').innerText") == 'My Tasks')
        # words
        await s.go('#/admin/custom', 400)
        await pg.fill('#cz-wl tr:has(input[value="Quick Win"]) [data-wt]', 'Improvement')
        await pg.locator('[data-csave=words]').click(); await pg.wait_for_timeout(500)
        nav = await J("document.querySelector('nav').innerText")
        c('word swapped in the menu (Quick Wins → Improvements)', 'Improvements' in nav and 'Quick Wins' not in nav, nav)
        t = await s.go('#/quickwins', 500); c('word swapped on the page', 'Quick win' not in t and 'Quick Win' not in t)
        t = await s.go('#/admin/custom', 400); c('Customize page itself keeps the original words', 'Quick Win' in t)
        # targets + weekend + welcome + report + start + tiles
        await pg.fill('#cz-t [name=teamScore]', '90'); await pg.fill('#cz-t [name=shadowHrs]', '12'); await pg.locator('[data-csave=targets]').click(); await pg.wait_for_timeout(400)
        c('targets read back', await J("Custom.target('teamScore')") == 90 and await J("Custom.target('shadowHrs')") == 12 and await J("Custom.target('hdDays')") == 3)
        await s.go('#/admin/custom', 300)
        await pg.locator('#cz-wk input[value="5"]').uncheck(); await pg.locator('#cz-wk input[value="0"]').check(); await pg.locator('[data-csave=weekend]').click(); await pg.wait_for_timeout(400)
        c('weekend = Sat/Sun', await J("U.isWeekend('2026-11-01') && U.isWeekend('2026-10-31') && !U.isWeekend('2026-10-30')"))
        await s.go('#/admin/custom', 300)
        await pg.fill('#cz-wel [name=welcome]', 'Log your shadow work before 3 pm.'); await pg.locator('[data-csave=welcome]').click(); await pg.wait_for_timeout(300)
        await s.go('#/admin/custom', 300)
        await pg.fill('#cz-rep [name=org]', 'APPS – Central Region'); await pg.fill('#cz-rep [name=footer]', 'Internal use'); await pg.locator('[data-csave=report]').click(); await pg.wait_for_timeout(300)
        await s.go('#/admin/custom', 300)
        await pg.select_option('#cz-st [name=analyst]', 'todo'); await pg.locator('[data-csave=start]').click(); await pg.wait_for_timeout(300)
        await s.go('#/admin/custom', 300)
        await pg.locator('#cz-tiles input[value=ytd]').uncheck(); await pg.locator('#cz-tiles input[value=hd]').uncheck(); await pg.locator('[data-csave=tiles]').click(); await pg.wait_for_timeout(300)
        bundle = await J("Custom.bundle()")
        c('export bundle holds everything', bundle['brand']['appName'] == 'MAHAMMI' and bundle['custom']['words']['Quick Win'] == 'Improvement' and bundle['custom']['start']['analyst'] == 'todo')
        await J("Store.flush && Store.flush()")
        # analyst view
        await s.sign_in_as('yousef'); await pg.wait_for_timeout(300)
        c('settings apply for an analyst too', await J("Store.appName()") == 'MAHAMMI' and await J("Custom.target('teamScore')") == 90)
        await J("App.chooseMe(true)"); await pg.wait_for_timeout(300)
        c('sign-in message shown', 'Log your shadow work before 3 pm.' in await J("document.body.innerText"))
        await J("UI.closeModal()")
        await J("history.replaceState(null,'','#/'); App.start ? 0 : 0")
        sp = await J("Custom.startPage('yousef')"); c('analyst start page = To Do list', sp == 'todo', sp)
        t = await s.go('#/home', 500)
        n = await J("document.querySelectorAll('#main .kpis .kpi').length")
        c('My Day shows 3 tiles', n == 3, n)
        c('shadow target 12 h on My Day', 'target ≥ 12 h' in t)
        c('Improvement word on My Day menu', 'Improvements' in await J("document.querySelector('nav').innerText"))
        await pg.screenshot(path=f'{SHOTS}/customize_analyst.png', full_page=True)
        # report header
        await s.sign_in_as('adam', 'admin'); await J("Store.save(Object.assign({}, Store.get('settings-perms') || {id:'settings-perms', c:'settings'}))")
        t = await s.go('#/reports', 600)
        c('report shows organisation and footer', 'APPS – Central Region' in t and 'Internal use' in t)
        # restore defaults + import back
        await s.go('#/admin/custom', 400)
        await pg.locator('#cz-all').click(); await pg.locator('.modal [data-yes]').click(); await pg.wait_for_timeout(500)
        c('restore all: words, menu, targets back to original', await J("Custom.target('teamScore')") == 80 and 'Quick Wins' in await J("document.querySelector('nav').innerText"))
        c('restore all keeps the app name', await J("Store.appName()") == 'MAHAMMI')
        n = await J(f"Custom.restore({__import__('json').dumps(bundle)})"); await pg.wait_for_timeout(300)
        c('bundle loads back', n >= 2 and await J("Custom.target('teamScore')") == 90 and await J("Custom.get('words',{})['Quick Win']") == 'Improvement')
        await s.go('#/admin/custom', 400)
        await pg.locator('[data-cdef=look]').click(); await pg.locator('.modal [data-yes]').click(); await pg.wait_for_timeout(500)
        c('restore name/logo/colour → DARRIK teal', await J("Store.appName()") == 'DARRIK' and await J("getComputedStyle(document.documentElement).getPropertyValue('--accent').trim()") == '#0e7c86')
        c.done(s)
run(main())
